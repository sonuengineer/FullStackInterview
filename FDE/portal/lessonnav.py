"""Adds navigation to every lesson file, from plan.json order. Safe to re-run (writes only on change).

  header : "> Core | Fast CP3 / Slow CP4 | ~1.2 h | Builds on: M06-12"
       -> "> **Core** | ~1.2 h | Slow: step 087/256, CP4 | Fast: CP3"
          ">"
          "> Before this: [M06-12 title](<...>)"
  ids    : every M06-12 outside code becomes a relative link to that lesson
  footer : "<- Prev | Syllabus CPn | Next ->" in slow-track order (between NAV_MARK and end of file)

Called from plan.build(); also runnable on its own: python portal/lessonnav.py
"""
import os
import re
from pathlib import Path

FDE = Path(__file__).resolve().parent.parent
NAV_MARK = "<!-- nav: generated by portal/lessonnav.py, do not edit below -->"
ID = re.compile(r"(?<![\[\w/-])(M\d\d-\d\d)(?![\w\]-])")
HEAD_OLD = re.compile(r"^> (Core|Extended \(slow track only\)|Diagnostic) \| (?:Fast CP\d+ / Slow CP\d+|Slow CP\d+ only) \| (.+)$")
HEAD_NEW = re.compile(r"^> \*\*(Core|Extended \(slow track only\)|Diagnostic)\*\* \| ")


def id_files():
    """M06-12 -> FDE-relative path, for every NN - folder (includes out-of-plan stubs)."""
    out = {}
    for folder in FDE.glob("[0-9][0-9] - *"):
        for f in folder.glob("[0-9][0-9] - *.md"):
            out[f"M{folder.name[:2]}-{f.name[:2]}"] = f.relative_to(FDE)
    return out


def rel(frm, to):
    return Path(os.path.relpath(FDE / to, (FDE / frm).parent)).as_posix()


def link_ids(text, here, files):
    """Link ids outside fenced code and inline code."""
    def sub_plain(seg):
        parts = re.split(r"(`[^`\n]*`)", seg)
        for k in range(0, len(parts), 2):
            parts[k] = ID.sub(lambda m: f"[{m.group(1)}](<{rel(here, files[m.group(1)])}>)" if m.group(1) in files and files[m.group(1)] != here else m.group(1), parts[k])
        return "".join(parts)
    chunks = re.split(r"(```.*?```)", text, flags=re.S)
    return "".join(sub_plain(c) if i % 2 == 0 else c for i, c in enumerate(chunks))


def placement(id_, pos):
    s, f = pos["slow"].get(id_), pos["fast"].get(id_)
    slow = f"Slow: step {s[0]:03d}/{s[2]}, CP{s[1]}" if s else "Slow: not in plan"
    fast = f"Fast: CP{f[1]}" if f else "Fast: not included"
    return f"{slow} | {fast}"


def rewrite_header(lines, id_, pos, items_ctx):
    for k, line in enumerate(lines[:12]):
        m_old, m_new = HEAD_OLD.match(line), HEAD_NEW.match(line)
        if not (m_old or m_new):
            continue
        if m_old:
            tier, rest = m_old.group(1), m_old.group(2).split(" | ")
        else:
            parts = line[2:].split(" | ")
            tier = parts[0].strip("*")
            rest = [p for p in parts[1:] if not p.startswith(("Slow: ", "Fast: "))]
        builds = [p for p in rest if p.startswith("Builds on: ")]
        keep = [p for p in rest if not p.startswith("Builds on: ")]
        lines[k] = f"> **{tier}** | " + " | ".join(keep[:1] + [placement(id_, pos)] + keep[1:])
        if builds:
            here, files = items_ctx
            before = "> Before this: " + ID.sub(
                lambda m: f"[{m.group(1)} {files[m.group(1)].stem.split(' - ', 1)[1]}](<{rel(here, files[m.group(1)])}>)"
                if m.group(1) in files else m.group(1), builds[0][len("Builds on: "):])
            lines[k + 1:k + 1] = [">", before]
        # blank ">" between the two lines, or markdown merges them into one paragraph
        if k + 1 < len(lines) and lines[k + 1].startswith("> Before this: "):
            lines.insert(k + 1, ">")
        return lines
    return lines


def footer(id_, here, seq, items, n_total):
    i = seq.index(id_)
    cp = items[id_]["_cp"]

    def step(j, arrow):
        if not 0 <= j < len(seq):
            return None
        it = items[seq[j]]
        label = f"step {j + 1:03d}"
        if it.get("file"):
            return f"{arrow} [{label}: {it['title']}](<{rel(here, it['file'])}>)"
        kind = {"build": "BUILD", "gate": "GATE", "setup": "SETUP"}.get(it["kind"], "")
        return f"{arrow} {label} {kind}: {it['title']} -- see [syllabus](<{rel(here, 'SYLLABUS.md')}#cp{it['_cp']}>)"
    prev, nxt = step(i - 1, "<- Prev:"), step(i + 1, "Next ->")
    # if the very next step is a build/gate, also point at the next lesson after it
    after = ""
    if nxt and not items[seq[i + 1]].get("file"):
        k = next((j for j in range(i + 2, len(seq)) if items[seq[j]].get("file")), None)
        if k is not None:
            after = f"\n- then lesson: [step {k + 1:03d}: {items[seq[k]]['title']}](<{rel(here, items[seq[k]]['file'])}>)"
    out = [NAV_MARK, "", "---", "",
           f"**Slow track, step {i + 1:03d} of {n_total}** -- [Syllabus CP{cp}](<{rel(here, 'SYLLABUS.md')}#cp{cp}>) | [START_HERE](<{rel(here, 'START_HERE.md')}>)", ""]
    out += [f"- {x}" for x in (prev, nxt) if x]
    return "\n".join(out) + after + "\n"


def apply(plan):
    items = {k: dict(v) for k, v in plan["items"].items()}
    pos = {}
    for name, T in plan["tracks"].items():
        seq = [i for c in T["checkpoints"] for i in c["items"]]
        pos[name] = {}
        for c in T["checkpoints"]:
            for i in c["items"]:
                pos[name][i] = (seq.index(i) + 1, c["n"], len(seq))
                if name == "slow":
                    items[i]["_cp"] = c["n"]
    seq = [i for c in plan["tracks"]["slow"]["checkpoints"] for i in c["items"]]
    by_file = {it["file"]: k for k, it in items.items() if it.get("file")}
    files = id_files()
    changed = 0
    targets = sorted(FDE.glob("[0-9][0-9] - */[0-9][0-9] - *.md")) + sorted(FDE.glob("Projects/*/[0-9][0-9] - *.md"))
    for f in targets:
        here = f.relative_to(FDE)
        old = f.read_text(encoding="utf-8")
        body = old.split(NAV_MARK)[0].rstrip() + "\n"
        id_ = by_file.get(here.as_posix())
        lines = body.split("\n")
        if id_:
            lines = rewrite_header(lines, id_, pos, (here, files))
        body = link_ids("\n".join(lines), here, files)
        if id_ in seq:
            body = body.rstrip() + "\n\n" + footer(id_, here, seq, items, len(seq))
        elif here.parts[0] == "Projects":
            body = body.rstrip() + "\n\n" + "\n".join([NAV_MARK, "", "---", "",
                f"[Project README](<README.md>) | [Syllabus](<{rel(here, 'SYLLABUS.md')}>) | [START_HERE](<{rel(here, 'START_HERE.md')}>)", ""])
        if body != old:
            f.write_text(body, encoding="utf-8")
            changed += 1
    return changed


if __name__ == "__main__":
    import json
    plan = json.loads((FDE / "portal" / "plan.json").read_text(encoding="utf-8"))
    print("lessons updated:", apply(plan))
